// Deterministic quality gates. A generation run is accepted only if every gate passes.
import { spawn, spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { childEnv } from './paths.mjs';
import { generatedFiles, isGenerated, isHarnessOutput, resolveCmd } from './target.mjs';
import { extractRequirements, scenarioCoverage } from './spec.mjs';
import { scaffoldDrift } from './scaffold.mjs';

/** Runs a command, streaming to a log file; resolves {ok, code, tail}. */
export function runCommand(cmd, { cwd, logFile, timeoutMs = 20 * 60_000 }) {
  const [rawBin, ...args] = resolveCmd(cmd, cwd);
  const bin = process.platform === 'win32' && /\s/.test(rawBin) ? `"${rawBin}"` : rawBin;
  return new Promise((resolve) => {
    const child = spawn(bin, args, { cwd, env: childEnv(), shell: process.platform === 'win32' });
    let out = '';
    const onData = (d) => {
      out += d;
      if (out.length > 2_000_000) out = out.slice(-1_000_000);
    };
    child.stdout.on('data', onData);
    child.stderr.on('data', onData);
    const timer = setTimeout(() => child.kill(), timeoutMs);
    child.on('close', (code) => {
      clearTimeout(timer);
      if (logFile) writeFileSync(logFile, out);
      resolve({ ok: code === 0, code, tail: tailLines(out, 80) });
    });
    child.on('error', (err) => {
      clearTimeout(timer);
      resolve({ ok: false, code: -1, tail: String(err) });
    });
  });
}

export const tailLines = (s, n) => s.split(/\r?\n/).slice(-n).join('\n');

/**
 * Project-relative paths under projectDir that differ from git HEAD (modified, deleted or untracked).
 * The project is a folder of the one repository, so status is limited to it (`-- .`) and git's
 * repo-relative paths are made project-relative by stripping the folder prefix.
 */
export function changedPaths(projectDir) {
  const prefix = spawnSync('git', ['rev-parse', '--show-prefix'], { cwd: projectDir, encoding: 'utf8' }).stdout.trim();
  const r = spawnSync('git', ['status', '--porcelain=v1', '-uall', '-z', '--', '.'], { cwd: projectDir, encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`git status failed in ${projectDir}: ${r.stderr}`);
  const entries = r.stdout.split('\0').filter(Boolean);
  const paths = [];
  for (let i = 0; i < entries.length; i++) {
    const e = entries[i];
    const p = e.slice(3);
    paths.push(p.startsWith(prefix) ? p.slice(prefix.length) : p);
    if (e[0] === 'R' || e[0] === 'C') i++; // rename/copy: next entry is the source path
  }
  return paths;
}

/** Boundary gate: nothing outside the generated roots (and harness outputs) may differ from HEAD. */
export function boundaryGate(target) {
  const violations = changedPaths(target.projectDir).filter((p) => !isGenerated(target, p) && !isHarnessOutput(target, p));
  if (target.scaffold) {
    // The scaffold must also equal its template (harness/scaffolds/<target>), the single source of truth.
    const { changed, extra } = scaffoldDrift(target);
    violations.push(...changed.map((p) => `${p} (differs from ${target.scaffold})`), ...extra.map((p) => `${p} (not in ${target.scaffold})`));
  }
  return {
    name: 'boundary',
    ok: violations.length === 0,
    tail: violations.length
      ? `Files outside the regeneration boundary were changed (scaffold is human-owned):\n${violations.map((v) => `  - ${v}`).join('\n')}`
      : 'only generated roots changed',
  };
}

/**
 * Traceability gate: every [client] requirement in the composed spec must be referenced by at least
 * one test file of the target. Writes TRACEABILITY.md (also lists [ui] → scenario coverage).
 */
export function traceabilityGate(target, bundle) {
  const reqs = extractRequirements(bundle.text);
  const testRe = new RegExp(target.tests.pattern);
  const testFiles = generatedFiles(target).filter(
    (f) => target.tests.include.some((i) => f.startsWith(i)) && testRe.test(f),
  );
  const contents = testFiles.map((f) => ({ f, text: readFileSync(join(target.projectDir, f), 'utf8') }));
  const refs = (id) => contents.filter((c) => new RegExp(`\\b${id}\\b`).test(c.text)).map((c) => c.f);

  const client = reqs.filter((r) => r.tags.includes('client'));
  const ui = reqs.filter((r) => r.tags.includes('ui'));
  const coverage = scenarioCoverage();
  const missing = client.filter((r) => refs(r.id).length === 0);
  const uncoveredUi = ui.filter((r) => !(coverage.get(r.id)?.length));

  const lines = [
    '<!-- @generated by chatgen-harness (traceability gate). Do not edit. -->',
    `# Traceability: ${target.id}`,
    '',
    `Spec hash \`${bundle.shortHash}\`. Every \`[client]\` requirement must be referenced by at least one unit test;`,
    '`[ui]` requirements are verified by the cross-platform scenarios in `spec/scenarios/`.',
    '',
    '| Requirement | Tag | Verified by |',
    '|---|---|---|',
    ...client.map((r) => `| ${r.id} | client | ${refs(r.id).map((f) => `\`${f}\``).join('<br>') || '**MISSING**'} |`),
    ...ui.map((r) => `| ${r.id} | ui | ${(coverage.get(r.id) ?? []).map((s) => `scenario \`${s}\``).join('<br>') || '**MISSING**'} |`),
    '',
  ];
  writeFileSync(join(target.projectDir, 'TRACEABILITY.md'), lines.join('\n'));

  const problems = [
    ...missing.map((r) => `  - ${r.id} [client] (${r.file}) has no unit test referencing it`),
    ...uncoveredUi.map((r) => `  - ${r.id} [ui] (${r.file}) is not covered by any scenario (spec problem, not a client problem)`),
  ];
  return {
    name: 'traceability',
    ok: problems.length === 0,
    tail: problems.length
      ? `Requirements without verification:\n${problems.join('\n')}\nAdd tests whose name or comment contains the requirement ID.`
      : `${client.length} client requirements traced to tests, ${ui.length} ui requirements traced to scenarios`,
  };
}

/** Runs the command gates declared in the target descriptor, in order, stopping at the first failure. */
export async function commandGates(target, runDir, attempt) {
  const results = [];
  for (const g of target.gates) {
    const started = Date.now();
    const r = await runCommand(g.cmd, { cwd: target.projectDir, logFile: join(runDir, `gate-${g.name}-${attempt}.log`) });
    results.push({ name: g.name, ok: r.ok, tail: r.tail, ms: Date.now() - started });
    if (!r.ok) break;
  }
  return results;
}
